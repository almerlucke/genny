package spec

import (
	"fmt"
	"strings"
)

// Reference returns the reference of the spec format as Markdown, built from the table of kinds, so it
// is always as complete as `genny list`. It is written to docs/spec-reference.md by `genny doc`; a test
// checks that the file in the repository is up to date.
func Reference() string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	w("# The genny spec format\n\n")
	w("<!-- Generated by `genny doc` from the table of kinds: do not edit by hand. -->\n\n")
	w("A spec is a JSON document that describes a piece. `genny render spec.json -o out.mid` turns it into a MIDI\n")
	w("file, `genny validate` only checks it and `genny list [kind]` prints the kinds in the terminal. The same spec\n")
	w("and seed always give the same file. Unknown fields, wrong types and out of range values are errors, and\n")
	w("every error names the JSON path of the problem, for example `tracks[1].source.params.length: must be > 0, got 0`.\n\n")

	w("## The spec\n\n```json\n{\n")
	w("  \"tempo\": 120, \"steps_per_beat\": 4, \"seed\": 7,\n")
	w("  \"time_signature\": {\"num\": 4, \"den\": 4},\n")
	w("  \"tracks\": [\n")
	w("    {\"name\": \"lead\", \"channel\": 0, \"program\": 80, \"pitch_bend\": false, \"source\": NODE}\n")
	w("  ]\n}\n```\n\n")
	w("| Field | Type | Default | Meaning |\n|---|---|---|---|\n")
	w("| `tempo` | number | 120 | beats per minute, above 0 and at most %d |\n", maxTempo)
	w("| `steps_per_beat` | number | 4 | steps in a beat (4 = sixteenth notes); the unit of all times below is the step |\n")
	w("| `seed` | integer | 1 | seed of the random stream; `-seed` on the command line overrides it |\n")
	w("| `time_signature` | object | none | `{\"num\", \"den\"}`, written to the file for the player |\n")
	w("| `tracks` | array | required | up to %d tracks |\n\n", maxTracks)
	w("A track:\n\n")
	w("| Field | Type | Default | Meaning |\n|---|---|---|---|\n")
	w("| `name` | string | | track name |\n")
	w("| `channel` | integer | 0 | MIDI channel 0..15 (9 is the General MIDI drum channel) |\n")
	w("| `program` | integer | 0 | instrument (General MIDI program) 0..127 |\n")
	w("| `pitch_bend` | boolean | false | play fractional pitches with pitch bend (only for lines of single notes) |\n")
	w("| `source` | node | required | the tree of nodes that makes the notes of the track |\n\n")

	w("## Nodes\n\n")
	w("A node is `{\"kind\": NAME, \"params\": {...}}`. A *generator* makes a line of notes from its parameters. A\n")
	w("*combinator* takes one child node in `item` or several in `items` and combines or transforms what they make,\n")
	w("so nodes nest:\n\n")
	w("```json\n")
	w("{\"kind\": \"concat\", \"params\": {\"items\": [\n")
	w("  {\"kind\": \"melody\", \"params\": {\"scale\": \"minor\", \"root\": \"D3\", \"length\": 32}},\n")
	w("  {\"kind\": \"transpose\", \"params\": {\"semitones\": 7, \"item\":\n")
	w("    {\"kind\": \"euclid\", \"params\": {\"pulses\": 5, \"steps\": 8, \"pitch\": 36, \"length\": 32}}}}\n")
	w("]}}\n```\n\n")
	w("Every node makes a *line*: note events (pitch, velocity, start and duration in steps) and a length in steps.\n")
	w("`concat` and `repeat` place lines one after the other using that length, which can be longer than the end of\n")
	w("the last note. A missing `params` is the same as an empty one, and every parameter that has a default can be left\n")
	w("out.\n\n")
	w("Value types used below:\n\n")
	w("- **pitch**: a MIDI note number (`60`, `61.5` for a microtone) or a note name (`C4` is 60, `F#3`, `Bb2`, `C-1` is 0).\n")
	w("- **scale**: a name or an array of semitone steps from the root, such as `[0, 2, 3, 5, 7, 8, 11]`. Names: %s.\n", codeList(ScaleNames()))
	w("- **sieve**: an expression of residue classes `mod@start` joined by `&` (and), `|` (or), `-` (difference), `!`\n")
	w("  (complement) and parentheses, for example `(3@0|5@1)&!2@0`.\n")
	w("- **node**: another node. **int**, **number**, **string**, **bool** and **array** are as in JSON.\n\n")
	w("Limits keep a spec from asking for unbounded work: lines of at most %d steps, %d notes in one generator, %d in\n", maxSteps, maxNodeNotes, maxTotalNotes)
	w("a render, nodes nested at most %d deep, specs up to %d MiB.\n\n", maxDepth, maxSpecBytes>>20)

	var all []Kind
	for _, cat := range []string{"generator", "combinator"} {
		w("## %ss\n\n", strings.ToUpper(cat[:1])+cat[1:])
		w("| Kind | What it does |\n|---|---|\n")
		var ofCat []Kind
		for _, k := range Kinds() {
			if k.Category == cat {
				ofCat = append(ofCat, k)
				w("| [`%s`](#%s) | %s |\n", k.Name, k.Name, cell(k.Doc))
			}
		}
		w("\n")
		all = append(all, ofCat...)
		for _, k := range ofCat {
			w("### %s\n\n%s\n\n", k.Name, sentence(k.Doc))
			if len(k.Params) == 0 {
				w("No parameters.\n\n")
				continue
			}
			w("| Parameter | Type | Default | Meaning |\n|---|---|---|---|\n")
			for _, p := range k.Params {
				def := "**required**"
				if p.Default != "" {
					def = "`" + p.Default + "`"
				}
				w("| `%s` | %s | %s | %s |\n", p.Name, cell(p.Type), cell(def), cell(p.Doc))
			}
			w("\n")
		}
	}

	w("## Examples\n\n")
	w("The specs in `examples/spec/` are complete pieces: `groove.json` (melody, bass and Euclidean drums, with swing),\n")
	w("`serial.json` (a tone row and its transformations) and `cloud.json` (a stochastic cloud).\n\n")
	w("## Adding a kind\n\n")
	w("All %d kinds are in one table, filled by `spec.Register` (see `spec/kinds_gen.go` and `spec/kinds_comb.go`). A\n", len(all))
	w("kind is a name, a category, a doc, the documentation of its parameters (which become the tables above) and a\n")
	w("build function. Regenerate this page with `go run ./cmd/genny doc > docs/spec-reference.md`.\n")
	return b.String()
}

func codeList(names []string) string {
	out := make([]string, len(names))
	for i, n := range names {
		out[i] = "`" + n + "`"
	}
	return strings.Join(out, ", ")
}

// cell makes text safe inside a table cell
func cell(s string) string { return strings.ReplaceAll(strings.ReplaceAll(s, "|", "\\|"), "\n", " ") }

// sentence capitalises the first letter of a doc line and makes sure it ends with a full stop
func sentence(s string) string {
	if s == "" {
		return s
	}
	s = strings.ToUpper(s[:1]) + s[1:]
	if !strings.HasSuffix(s, ".") {
		s += "."
	}
	return s
}
